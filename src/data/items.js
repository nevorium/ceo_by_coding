/**
 * Get item metadata by id, falling back to a formatted default if missing.
 * @param {string} id
 * @returns {typeof ITEMS[keyof typeof ITEMS]}
 */
export function getItem(id) {
  if (ITEMS[id]) return ITEMS[id];
  const formatted = id.replaceAll('_', ' ');
  return {
    id,
    name: formatted.charAt(0).toUpperCase() + formatted.slice(1),
    emoji: '',
    desc: formatted,
    rarity: 'Common',
    category: 'Umum',
    sector: 'Umum',
    stackMax: 99,
    stackMaxWarehouse: 999,
  };
}

